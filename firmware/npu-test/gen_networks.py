#!/usr/bin/env python3
"""Converts Vela raw output (<name>_vela.npz, --output-format raw) into C headers for npu-test.

    gen_networks.py --out networks/ NAME=path/to/NAME_vela.npz ...

Per network it writes networks/net_<NAME>.h with the driver payload (COP1 header + register
command stream), the encoded weights, a deterministic pseudo-random input (xorshift32, seed derived
from the network's index) and a `struct network` descriptor; networks/networks.h includes them all
in the given order and defines the `networks[]` table. Blobs are emitted as little-endian uint32
words in the `.netdata` section (DDR). Needs numpy (the Vela venv has it).
"""
import argparse
import os
import sys

import numpy as np


def fnv1a(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def xorshift_bytes(seed: int, n: int) -> bytes:
    x = seed & 0xFFFFFFFF
    out = bytearray()
    while len(out) < n:
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out.append(x & 0xFF)
    return bytes(out)


def words(data: bytes):
    pad = (-len(data)) % 4
    data = data + b"\0" * pad
    return np.frombuffer(data, dtype="<u4")


def emit_array(f, name, data: bytes, section=True):
    w = words(data)
    attr = ' __attribute__((aligned(16), section(".netdata")))' if section else ' __attribute__((aligned(16)))'
    f.write(f"static const uint32_t {name}[{len(w)}]{attr} = {{\n")
    for i in range(0, len(w), 8):
        f.write("  " + ", ".join(f"0x{v:08x}" for v in w[i:i + 8]) + ",\n")
    f.write("};\n")


def shape_size(shape, elem):
    return int(np.prod([int(s) for s in shape])) * int(elem)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("nets", nargs="+", help="NAME=path/to/NAME_vela.npz")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    table = []
    for index, spec in enumerate(args.nets):
        name, path = spec.split("=", 1)
        d = np.load(path, allow_pickle=True)
        cmd = bytes(d["cmd_data"].tobytes())
        weights = bytes(d["weight_data"].tobytes())
        assert cmd[:4] == b"COP1", f"{path}: cmd_data is not a COP1 driver payload"
        assert len(d["input_shape"]) == 1 and len(d["output_shape"]) == 1, f"{path}: one input and one output expected"
        in_size = shape_size(d["input_shape"][0], d["input_elem_size"][0])
        out_size = shape_size(d["output_shape"][0], d["output_elem_size"][0])
        in_off, out_off = int(d["input_offset"][0]), int(d["output_offset"][0])
        in_reg, out_reg = int(d["input_region"][0]), int(d["output_region"][0])
        wreg, sreg, freg = int(d["weight_region"]), int(d["scratch_region"]), int(d["scratch_fast_region"])
        scratch, fast = int(d["scratch_size"]), int(d["scratch_fast_size"])
        assert (wreg, sreg, freg) == (0, 1, 2), f"{path}: regions {wreg},{sreg},{freg} (expected 0,1,2 = Dedicated_Sram)"
        assert in_reg == 1 and out_reg == 1, f"{path}: input/output not in the arena region"
        assert len(d["variable_shape"]) == 0, f"{path}: variable tensors are not supported"
        seed = 0x9E3779B9 ^ (0x01000193 * (index + 1)) & 0xFFFFFFFF
        inp = xorshift_bytes(seed, in_size)
        hdr = os.path.join(args.out, f"net_{name}.h")
        with open(hdr, "w") as f:
            f.write(f"/* Generated by gen_networks.py from {os.path.basename(path)}; do not edit.\n")
            f.write(f"   cmd {len(cmd)} B (fnv1a 0x{fnv1a(cmd):08x}), weights {len(weights)} B (fnv1a 0x{fnv1a(weights):08x}),\n")
            f.write(f"   input {list(int(s) for s in d['input_shape'][0])} x{int(d['input_elem_size'][0])} B at arena+{in_off} (xorshift32 seed 0x{seed:08x}, fnv1a 0x{fnv1a(inp):08x}),\n")
            f.write(f"   output {list(int(s) for s in d['output_shape'][0])} x{int(d['output_elem_size'][0])} B at arena+{out_off},\n")
            f.write(f"   scratch (region 1) {scratch} B, fast scratch (region 2) {fast} B, weights in region 0. */\n")
            f.write("#include <stdint.h>\n#include \"npu_test.h\"\n\n")
            emit_array(f, f"{name}_cmd", cmd)
            emit_array(f, f"{name}_weights", weights)
            emit_array(f, f"{name}_input", inp)
            f.write(f"\nstatic const struct network {name}_net = {{\n")
            f.write(f'  .name = "{name}",\n')
            f.write(f"  .cmd = {name}_cmd, .cmd_size = {len(cmd)},\n")
            f.write(f"  .weights = {name}_weights, .weights_size = {len(weights)},\n")
            f.write(f"  .input = {name}_input, .input_size = {in_size}, .input_offset = {in_off},\n")
            f.write(f"  .output_size = {out_size}, .output_offset = {out_off},\n")
            f.write(f"  .scratch_size = {scratch}, .fast_size = {fast},\n")
            f.write("};\n")
        table.append(name)
        print(f"{hdr}: cmd {len(cmd)} weights {len(weights)} in {in_size}@{in_off} out {out_size}@{out_off} "
              f"scratch {scratch} fast {fast} input_fnv 0x{fnv1a(inp):08x} weights_fnv 0x{fnv1a(weights):08x}")
    with open(os.path.join(args.out, "networks.h"), "w") as f:
        f.write("/* Generated by gen_networks.py; do not edit. */\n")
        for name in table:
            f.write(f'#include "net_{name}.h"\n')
        f.write("\nstatic const struct network *const networks[] = {\n")
        for name in table:
            f.write(f"  &{name}_net,\n")
        f.write("};\n#define NUM_NETWORKS (sizeof(networks) / sizeof(networks[0]))\n")


if __name__ == "__main__":
    sys.exit(main())
